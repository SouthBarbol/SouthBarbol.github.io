// Current language (default: Spanish)
let currentLang = 'es';

/**
 * Get translation for a key path
 * @param {string} keyPath - Dot notation key path (e.g., 'header.home')
 * @returns {string} - Translated text
 */
function t(keyPath) {
  const keys = keyPath.split('.');
  let value = translations;
  
  for (const key of keys) {
    if (value && typeof value === 'object' && key in value) {
      value = value[key];
    } else {
      console.warn(`Translation not found: ${keyPath}`);
      return keyPath;
    }
  }
  
  if (typeof value === 'object' && value[currentLang]) {
    return value[currentLang];
  }
  
  return typeof value === 'string' ? value : keyPath;
}

/**
 * Set current language
 * @param {string} lang - Language code ('es' or 'en')
 */
function setLanguage(lang) {
  if (lang === 'es' || lang === 'en') {
    currentLang = lang;
    localStorage.setItem('portfolioLang', lang);
    updatePageTranslations();
  }
}

/**
 * Get current language
 * @returns {string} - Current language code
 */
function getLanguage() {
  return currentLang;
}

/**
 * Initialize language from localStorage or default
 */
function initLanguage() {
  const savedLang = localStorage.getItem('portfolioLang');
  if (savedLang === 'es' || savedLang === 'en') {
    currentLang = savedLang;
  }
  updatePageTranslations();
}

/**
 * Update all translatable elements on the page
 */
function updatePageTranslations() {
  // Update all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    const translation = t(key);
    if (translation !== key) {
      element.textContent = translation;
    }
  });
  
  // Update placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
    const key = element.getAttribute('data-i18n-placeholder');
    const translation = t(key);
    if (translation !== key) {
      element.placeholder = translation;
    }
  });
  
  // Update language selector UI
  updateLanguageSelector();
}

/**
 * Update the language selector visual state
 */
function updateLanguageSelector() {
  const selector = document.getElementById('lang-selector');
  if (selector) {
    const buttons = selector.querySelectorAll('.lang-btn');
    buttons.forEach(btn => {
      if (btn.getAttribute('data-lang') === currentLang) {
        btn.classList.add('active');
      } else {
        btn.classList.remove('active');
      }
    });
  }
}

// Export functions for global use
window.translations = translations;
window.t = t;
window.setLanguage = setLanguage;
window.getLanguage = getLanguage;
window.initLanguage = initLanguage;
window.updatePageTranslations = updatePageTranslations;